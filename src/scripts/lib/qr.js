// Exchange pass QR helpers (visual-language T10c-1): encode a code string
// into a real, scannable QR module matrix (uqr, error correction H so a
// centered logo can cover a few modules) and turn the matrix into an SVG
// path or canvas drawing. Pure apart from the canvas helper.
import { encode } from "uqr";

/**
 * Encodes `text` at error-correction level H without a border.
 * @param {string} text
 * @returns {{ matrix: boolean[][], size: number, version: number }}
 */
export function qrMatrix(text) {
  const { data, size, version } = encode(text, { ecc: "H", border: 0 });
  return { matrix: data, size, version };
}

/**
 * Centered square of modules reserved for the logo: the largest odd count
 * that is at most `ratio` of the code width (odd so it centers exactly on
 * an odd-sized symbol). Half-open range [start, end) on both axes.
 * @param {number} size
 * @param {number} [ratio]
 */
export function logoArea(size, ratio = 0.2) {
  let count = Math.floor(size * ratio);
  if (count % 2 === 0) count -= 1;
  count = Math.max(1, count);
  const start = (size - count) / 2;
  return { start, end: start + count };
}

/** @param {{ start: number, end: number } | null | undefined} area */
export function isInArea(x, y, area) {
  if (!area) return false;
  return x >= area.start && x < area.end && y >= area.start && y < area.end;
}

/**
 * SVG path data for the dark modules, one rectangle per horizontal run, in
 * module units (viewBox `0 0 size+2*margin size+2*margin`).
 * @param {boolean[][]} matrix
 * @param {{ margin?: number, clear?: { start: number, end: number } | null }} [options]
 */
export function qrPath(matrix, { margin = 0, clear = null } = {}) {
  let d = "";
  matrix.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (!row[x] || isInArea(x, y, clear)) {
        x += 1;
        continue;
      }
      const runStart = x;
      while (x < row.length && row[x] && !isInArea(x, y, clear)) x += 1;
      const len = x - runStart;
      d += `M${runStart + margin} ${y + margin}h${len}v1h-${len}z`;
    }
  });
  return d;
}

/**
 * Issue date embedded in codes generated by detail.js (`MINKA-DET-<ms>-…`)
 * and publish.js (`MINKA-<ms>-…`); null when the code carries none.
 * @param {string} code
 * @returns {Date | null}
 */
export function codeIssuedAt(code) {
  const match = /^MINKA-(?:DET-)?(\d{13})-/.exec(code || "");
  return match ? new Date(Number(match[1])) : null;
}

/**
 * Draws the code onto a square canvas: light background, dark modules with
 * a quiet zone of `margin` modules, and the logo area left light.
 * @param {CanvasRenderingContext2D} ctx
 * @param {boolean[][]} matrix
 * @param {{ px: number, margin?: number, dark?: string, light?: string,
 *   clear?: { start: number, end: number } | null }} options
 */
export function drawQr(ctx, matrix, { px, margin = 4, dark = "#000000", light = "#ffffff", clear = null }) {
  const cell = px / (matrix.length + margin * 2);
  ctx.fillStyle = light;
  ctx.fillRect(0, 0, px, px);
  ctx.fillStyle = dark;
  matrix.forEach((row, y) => {
    row.forEach((on, x) => {
      if (!on || isInArea(x, y, clear)) return;
      // Round outward so neighbouring modules never leave hairline gaps.
      const left = Math.floor((x + margin) * cell);
      const top = Math.floor((y + margin) * cell);
      ctx.fillRect(left, top, Math.ceil((x + margin + 1) * cell) - left, Math.ceil((y + margin + 1) * cell) - top);
    });
  });
  return cell;
}
